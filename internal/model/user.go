package model

// User описывает зарегистрированного пользователя. Пароль в открытом виде
// нигде не хранится.
type User struct {
	// ID - идентификатор пользователя, выдаётся при регистрации и больше
	// не меняется.
	ID int64
	// Login уникален с учётом регистра: gopher и Gopher считаются
	// разными пользователями.
	Login string
	// PasswordHash - bcrypt-хеш пароля вместе с солью.
	PasswordHash string
}
