package model

// User описывает зарегистрированного пользователя. Пароль в открытом виде
// нигде не хранится.
type User struct {
	// ID выдаёт база при регистрации. Он же зашит в токен доступа
	// и связывает пользователя с его заказами и списаниями.
	ID int64
	// Login уникален с учётом регистра: gopher и Gopher считаются
	// разными пользователями.
	Login string
	// PasswordHash задаёт bcrypt-хеш пароля вместе с солью. Сверяет его
	// auth.CheckPassword.
	PasswordHash string
}
