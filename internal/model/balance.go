package model

import "time"

// Balance описывает счёт баллов пользователя на момент запроса.
type Balance struct {
	// Current - баллы, доступные для списания: начисления по заказам
	// в статусе StatusProcessed за вычетом всех списаний. Отрицательным
	// не бывает.
	Current Money
	// Withdrawn - сумма всех списаний пользователя за всё время.
	Withdrawn Money
}

// Withdrawal описывает списание баллов в счёт оплаты заказа. Однажды
// записанное списание не меняется.
type Withdrawal struct {
	// Order - номер заказа, оплаченного баллами. Проходит проверку Луна,
	// но загружать его в Гофермарт не нужно, и один номер может встречаться
	// в нескольких списаниях.
	Order string
	// Sum - списанные баллы, округлённые до копейки. Всегда больше нуля.
	Sum Money
	// ProcessedAt - момент списания.
	ProcessedAt time.Time
}
