package model

import "time"

// Balance описывает счёт баллов пользователя. Остаток нигде не хранится:
// оба поля база считает при каждом запросе по заказам и списаниям.
type Balance struct {
	// Current задаёт баллы, доступные для списания: начисления по заказам
	// в статусе PROCESSED минус все списания. Отрицательным не бывает,
	// потому что списание сверх остатка отклоняется.
	Current Money
	// Withdrawn задаёт сумму всех списаний пользователя за всё время.
	Withdrawn Money
}

// Withdrawal описывает списание баллов в счёт оплаты заказа. Однажды
// записанное списание не меняется.
type Withdrawal struct {
	// Order задаёт номер заказа, который оплачен баллами. Он проходит
	// проверку Луна, но загружать его в Гофермарт не нужно, и один номер
	// может встречаться в нескольких списаниях.
	Order string
	// Sum задаёт списанные баллы, округлённые базой до копейки. Всегда
	// больше нуля.
	Sum Money
	// ProcessedAt задаёт момент списания, его ставит база при записи.
	// Списки списаний идут по нему от новых к старым, в JSON он выводится
	// в RFC3339.
	ProcessedAt time.Time
}
