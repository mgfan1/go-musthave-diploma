package model

import "time"

// OrderStatus задаёт этап расчёта начисления по заказу. Заказ появляется
// в StatusNew, может перейти в StatusProcessing и заканчивает в одном
// из окончательных статусов, StatusInvalid или StatusProcessed, после
// которых больше не меняется. Других значений схема базы не допускает.
type OrderStatus string

const (
	// StatusNew означает, что заказ загружен, но система расчёта о нём
	// ещё ничего не сообщила.
	StatusNew OrderStatus = "NEW"
	// StatusProcessing означает, что система расчёта знает о заказе
	// и считает начисление.
	StatusProcessing OrderStatus = "PROCESSING"
	// StatusInvalid означает, что система расчёта отказала в расчёте.
	// Статус окончательный.
	StatusInvalid OrderStatus = "INVALID"
	// StatusProcessed означает, что расчёт окончен и начисление, если оно
	// положено, уже учтено в балансе. Статус окончательный.
	StatusProcessed OrderStatus = "PROCESSED"
)

// Order описывает номер заказа, который пользователь загрузил, чтобы
// получить за него баллы. Номер принадлежит тому, кто загрузил его первым.
type Order struct {
	// Number задаёт номер заказа: ASCII-цифры любой длины, прошедшие
	// проверку Луна. Номер уникален среди всех пользователей.
	Number string
	// Status меняет только фоновый опрос системы расчёта. Статус и Accrual
	// записываются одним запросом, поэтому баланс не может увидеть PROCESSED
	// раньше начисленной суммы. Если система расчёта не прислала сумму, заказ
	// становится PROCESSED без Accrual и в балансе даёт ноль.
	Status OrderStatus
	// Accrual задаёт начисленные баллы с точностью до копейки. Заполнено
	// только у PROCESSED и только если система расчёта прислала сумму.
	// Nil означает, что начисления нет, и отличается от нуля: в JSON поле
	// с nil опускается, а ноль выводится.
	Accrual *Money
	// UploadedAt задаёт момент первой загрузки номера, его ставит база.
	// Повторная загрузка его не меняет. Списки заказов идут по нему от
	// новых к старым, в JSON он выводится в RFC3339.
	UploadedAt time.Time
}
